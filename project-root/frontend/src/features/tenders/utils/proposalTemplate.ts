/** Подставляет значения в шаблон. Неизвестные плейсхолдеры остаются как есть. */
export function renderProposalTemplate(values: Record<string, string>): string {
  return PROPOSAL_TEMPLATE.replace(/\{([А-ЯЁ0-9_]+)\}/g, (match, key: string) =>
    key in values ? values[key] : match
  );
}
